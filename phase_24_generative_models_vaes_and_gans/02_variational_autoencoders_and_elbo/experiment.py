#!/usr/bin/env python3
"""
Topic 24.2: Variational Autoencoders & The Evidence Lower Bound (ELBO)
======================================================================

This experiment verifies the core mathematical identity of Variational Inference:
  log p(x) = ELBO(phi, theta; x) + D_KL(q_phi(z | x) || p(z | x))

Because D_KL >= 0, it holds that:
  ELBO <= log p(x)

We build:
1. An analytically solvable toy latent variable system with exact marginal log p(x).
2. A parameterized variational family q_phi(z | x).
3. The exact analytical Gaussian KL divergence:
     D_KL(N(mu, diag(sigma^2)) || N(0, I)) = -0.5 * sum(1 + log(sigma^2) - mu^2 - sigma^2)
4. Numerical & analytical verification of ELBO <= log p(x) and convergence to equality
   as q_phi(z | x) converges to the true posterior p(z | x).

Zero external dependencies: Pure Python 3 standard library.
"""

import math
import random

random.seed(42)


# =====================================================================
# 1. Closed-Form Gaussian KL Divergence
# =====================================================================

def gaussian_kl_divergence(mu, log_var):
    """
    Computes D_KL( q(z) || p(z) ) where:
      q(z) = N(mu, diag(exp(log_var)))
      p(z) = N(0, I)
    Formula:
      -0.5 * sum_{j=1}^J (1 + log(sigma_j^2) - mu_j^2 - sigma_j^2)
    """
    kl = 0.0
    for m, lv in zip(mu, log_var):
        var = math.exp(lv)
        kl += -0.5 * (1.0 + lv - m ** 2 - var)
    return kl


# =====================================================================
# 2. Discrete Toy Latent Variable Model with Exact Marginal Likelihood
# =====================================================================

class DiscreteToyModel:
    """
    A 1D observed variable x in {0, 1, ..., K-1} generated by discrete latent z in {0, ..., M-1}.
    Prior: p(z)
    Likelihood: p(x | z)
    Joint: p(x, z) = p(x | z) * p(z)
    Marginal: p(x) = sum_z p(x, z)
    True Posterior: p(z | x) = p(x, z) / p(x)
    """
    def __init__(self, num_x=4, num_z=3):
        self.num_x = num_x
        self.num_z = num_z

        # Define prior p(z)
        raw_prior = [0.2, 0.5, 0.3]
        s = sum(raw_prior)
        self.p_z = [v / s for v in raw_prior]

        # Define emission likelihood p(x | z) matrix (num_z x num_x)
        self.p_x_given_z = [
            [0.6, 0.2, 0.1, 0.1],  # z = 0
            [0.1, 0.7, 0.1, 0.1],  # z = 1
            [0.05, 0.05, 0.4, 0.5]  # z = 2
        ]

    def joint(self, x, z):
        return self.p_x_given_z[z][x] * self.p_z[z]

    def marginal_likelihood(self, x):
        return sum(self.joint(x, z) for z in range(self.num_z))

    def true_posterior(self, x):
        px = self.marginal_likelihood(x)
        return [self.joint(x, z) / px for z in range(self.num_z)]

    def compute_elbo_and_kl(self, x, q_phi):
        """
        Given variational distribution q_phi(z | x), evaluates:
          ELBO = sum_z q(z) * log( p(x, z) / q(z) )
               = sum_z q(z) * log p(x | z) - D_KL( q(z) || p(z) )
          KL_posterior = D_KL( q_phi(z | x) || p(z | x) )
        """
        # Reconstruction term: E_q[log p(x | z)]
        recon = sum(q_phi[z] * math.log(max(self.p_x_given_z[z][x], 1e-15)) for z in range(self.num_z))

        # Latent prior KL: D_KL( q(z) || p(z) )
        kl_prior = sum(
            q_phi[z] * math.log(max(q_phi[z] / self.p_z[z], 1e-15))
            for z in range(self.num_z) if q_phi[z] > 0
        )

        elbo = recon - kl_prior

        # Posterior KL: D_KL( q(z) || p(z | x) )
        true_post = self.true_posterior(x)
        kl_post = sum(
            q_phi[z] * math.log(max(q_phi[z] / true_post[z], 1e-15))
            for z in range(self.num_z) if q_phi[z] > 0
        )

        return elbo, recon, kl_prior, kl_post


# =====================================================================
# 3. Continuous 1D Gaussian Toy Model
# =====================================================================

class ContinuousGaussianToy:
    """
    Latent prior: z ~ N(0, 1)
    Observation model: x | z ~ N(w * z, sigma_x^2)
    This is a linear Gaussian model where:
      True marginal: x ~ N(0, w^2 + sigma_x^2)
      True posterior: z | x ~ N(mu_post, var_post)
        mu_post = w * x / (w^2 + sigma_x^2)
        var_post = sigma_x^2 / (w^2 + sigma_x^2)
    """
    def __init__(self, w=1.5, sigma_x=0.8):
        self.w = w
        self.sigma_x = sigma_x
        self.var_x = sigma_x ** 2
        self.marginal_var = w ** 2 + self.var_x

    def log_true_marginal(self, x):
        """Exact log p(x) under marginal distribution N(0, w^2 + sigma_x^2)"""
        return -0.5 * math.log(2 * math.pi * self.marginal_var) - (x ** 2) / (2.0 * self.marginal_var)

    def true_posterior_params(self, x):
        mu_post = (self.w * x) / self.marginal_var
        var_post = self.var_x / self.marginal_var
        return mu_post, var_post

    def estimate_elbo_monte_carlo(self, x, q_mu, q_var, num_samples=10000):
        """
        ELBO = E_{q}[log p(x | z)] - D_KL(q(z) || p(z))
        Approximates the reconstruction expectation with Monte Carlo samples.
        """
        q_sigma = math.sqrt(q_var)
        recon_acc = 0.0
        for _ in range(num_samples):
            # Box-Muller transform for standard normal sample
            u1 = max(random.random(), 1e-12)
            u2 = random.random()
            eps = math.sqrt(-2.0 * math.log(u1)) * math.cos(2.0 * math.pi * u2)
            z = q_mu + q_sigma * eps

            # log p(x | z) where p(x|z) is N(w*z, sigma_x^2)
            mean_x = self.w * z
            log_p_xz = -0.5 * math.log(2 * math.pi * self.var_x) - ((x - mean_x) ** 2) / (2.0 * self.var_x)
            recon_acc += log_p_xz

        mc_recon = recon_acc / num_samples
        kl = gaussian_kl_divergence([q_mu], [math.log(q_var)])
        elbo = mc_recon - kl
        return elbo, mc_recon, kl


# =====================================================================
# Main Execution & Verification
# =====================================================================

def run_experiment():
    print("=" * 76)
    print("TOPIC 24.2: VARIATIONAL INFERENCE & ELBO MATHEMATICAL RIGOR")
    print("=" * 76)

    # -------------------------------------------------------------
    # 1. Closed-form Gaussian KL verification
    # -------------------------------------------------------------
    print("\n--- [1] Analytical Gaussian KL Divergence D_KL(N(mu, sigma^2) || N(0, 1)) ---")
    # Test case 1: identical distribution
    kl_zero = gaussian_kl_divergence([0.0], [0.0])
    print(f"  KL for q = N(0, 1), p = N(0, 1)        : {kl_zero:.8f} (Expected: 0.0)")
    assert abs(kl_zero) < 1e-10, "KL of identical distributions must be zero."

    # Test case 2: shifted mean mu = 2.0, var = 1.0 (log_var = 0.0)
    # Expected: -0.5 * (1 + 0 - 4 - 1) = -0.5 * (-4) = 2.0
    kl_shifted = gaussian_kl_divergence([2.0], [0.0])
    print(f"  KL for q = N(2, 1), p = N(0, 1)        : {kl_shifted:.8f} (Expected: 2.0)")
    assert abs(kl_shifted - 2.0) < 1e-10, "Shifted mean KL calculation error."

    # Test case 3: zero mean, scaled variance sigma^2 = 4 (log_var = ln(4) = 1.386294)
    # Expected: -0.5 * (1 + ln 4 - 0 - 4) = -0.5 * (ln 4 - 3) = 0.5 * (3 - 1.386294) = 0.8068528
    kl_scaled = gaussian_kl_divergence([0.0], [math.log(4.0)])
    expected_kl_scaled = 0.5 * (3.0 - math.log(4.0))
    print(f"  KL for q = N(0, 4), p = N(0, 1)        : {kl_scaled:.8f} (Expected: {expected_kl_scaled:.8f})")
    assert abs(kl_scaled - expected_kl_scaled) < 1e-10, "Scaled variance KL error."

    # -------------------------------------------------------------
    # 2. Exact Discrete Marginal Likelihood vs ELBO Decomposition
    # -------------------------------------------------------------
    print("\n--- [2] Verification of Identity: log p(x) = ELBO + D_KL(q || p(z|x)) ---")
    toy = DiscreteToyModel(num_x=4, num_z=3)
    target_x = 1

    p_x = toy.marginal_likelihood(target_x)
    log_p_x = math.log(p_x)
    true_post = toy.true_posterior(target_x)

    print(f"  Observed state x = {target_x}:")
    print(f"    True Marginal Likelihood p(x)       : {p_x:.6f}")
    print(f"    True Marginal Log-Likelihood log p(x): {log_p_x:.6f}")
    print(f"    True Posterior p(z | x)             : {[round(v, 4) for v in true_post]}")

    # Case A: Poor variational approximation q_A
    q_A = [0.70, 0.15, 0.15]
    elbo_A, recon_A, kl_prior_A, kl_post_A = toy.compute_elbo_and_kl(target_x, q_A)

    print(f"\n  [Candidate A: Suboptimal q_A(z|x) = {q_A}]")
    print(f"    Reconstruction E_q[log p(x|z)]      : {recon_A:.6f}")
    print(f"    Prior Regularizer D_KL(q || p(z))   : {kl_prior_A:.6f}")
    print(f"    ELBO_A                              : {elbo_A:.6f}")
    print(f"    Posterior Gap D_KL(q_A || p(z|x))   : {kl_post_A:.6f}")
    print(f"    Sum: ELBO + D_KL(q_A || p(z|x))      : {elbo_A + kl_post_A:.6f} == {log_p_x:.6f}")
    assert elbo_A <= log_p_x, "ELBO must be lower bound!"
    assert abs((elbo_A + kl_post_A) - log_p_x) < 1e-10, "Decomposition identity violation!"

    # Case B: Perfect variational approximation q_B = true_post
    q_B = true_post[:]
    elbo_B, recon_B, kl_prior_B, kl_post_B = toy.compute_elbo_and_kl(target_x, q_B)

    print(f"\n  [Candidate B: Exact Posterior q_B(z|x) = p(z|x)]")
    print(f"    Reconstruction E_q[log p(x|z)]      : {recon_B:.6f}")
    print(f"    Prior Regularizer D_KL(q || p(z))   : {kl_prior_B:.6f}")
    print(f"    ELBO_B                              : {elbo_B:.6f}")
    print(f"    Posterior Gap D_KL(q_B || p(z|x))   : {kl_post_B:.6f} (Gap Closed to Zero)")
    print(f"    ELBO_B == log p(x)                  : {abs(elbo_B - log_p_x) < 1e-10}")
    assert abs(kl_post_B) < 1e-10, "Posterior KL must be zero when q matches true posterior."
    assert abs(elbo_B - log_p_x) < 1e-10, "ELBO must equal log p(x) exactly when q = p(z|x)."

    # -------------------------------------------------------------
    # 3. Continuous 1D Gaussian System Verification
    # -------------------------------------------------------------
    print("\n--- [3] Continuous Gaussian Latent Model Monte Carlo Test ---")
    c_toy = ContinuousGaussianToy(w=1.5, sigma_x=0.8)
    x_obs = 1.2

    true_log_px = c_toy.log_true_marginal(x_obs)
    mu_true, var_true = c_toy.true_posterior_params(x_obs)

    print(f"  Observed continuous value x = {x_obs:.2f}:")
    print(f"    Exact Analytical Marginal log p(x)  : {true_log_px:.6f}")
    print(f"    Exact Posterior: mu* = {mu_true:.4f}, var* = {var_true:.4f}")

    # Test suboptimal variational distribution
    subopt_mu, subopt_var = 0.0, 1.0
    elbo_sub, _, kl_sub = c_toy.estimate_elbo_monte_carlo(x_obs, subopt_mu, subopt_var, num_samples=15000)
    print(f"\n  Suboptimal q ~ N(0, 1):")
    print(f"    Monte Carlo ELBO                    : {elbo_sub:.4f} <= True log p(x): {true_log_px:.4f}")
    assert elbo_sub <= true_log_px + 0.05, "Suboptimal ELBO exceeded true marginal!"

    # Test optimal variational distribution q = p(z|x)
    elbo_opt, _, kl_opt = c_toy.estimate_elbo_monte_carlo(x_obs, mu_true, var_true, num_samples=25000)
    print(f"\n  Optimal q ~ N(mu*, var*):")
    print(f"    Monte Carlo ELBO                    : {elbo_opt:.4f} (Approaching {true_log_px:.4f})")
    print(f"    Tightness Gap                       : {abs(true_log_px - elbo_opt):.4f}")

    print("\n" + "=" * 76)
    print("ALL VARIATIONAL INFERENCE IDENTITIES VERIFIED (Exit Code 0).")
    print("=" * 76)
    return True


if __name__ == "__main__":
    run_experiment()
